/**
 * normal-equations.ts —— 正规方程法求解线性最小二乘
 * ============================================================================
 *
 * 【问题】
 *   外层非线性迭代（LM/ODR）每轮都产生同一个线性子问题：
 *
 *       min_Δ ‖J·Δ − r‖²        J: m×n, r: m, Δ: n
 *
 *   即：在当前点的一阶泰勒近似下，找让残差平方和最小的参数步长 Δ。
 *   本模块就是这道线性题的“直接法”求解器之一。
 *
 * 【原理：从最小二乘到正规方程】
 *   对 Δ 求导并令其为零：
 *       ∂/∂Δ ‖JΔ − r‖² = 2·Jᵀ(JΔ − r) = 0
 *   得到 n×n 的线性方程组——正规方程（normal equations）：
 *
 *       (JᵀJ)·Δ = Jᵀr
 *
 *   JᵀJ 是对称正定阵（J 列满秩时），它近似目标函数的 Hessian；
 *   Jᵀr 是梯度的反向，即最速下降方向按曲率加权后的结果。
 *
 * 【原理：为什么用 Cholesky 而不是高斯消元】
 *   JᵀJ 对称正定，Cholesky 分解 A = L·Lᵀ（L 下三角）恰好利用这一性质：
 *   - 计算量是高斯消元的一半（n³/3 vs 2n³/3 flops）；
 *   - 不需要选主元（正定性保证数值稳定）；
 *   - 分解后前代+回代各 O(n²) 即得解。
 *
 * 【阻尼（LM 的核心机制）】
 *   实际解的是 (JᵀJ + λD)·Δ = Jᵀr：
 *   - λ→0：退化为纯 Gauss-Newton，步子大但可能发散；
 *   - λ→∞：退化为梯度下降，步子小而保守；
 *   - D 默认取 JᵀJ 的对角元（Marquardt 尺度归一化）：让每个参数的阻尼
 *     相对自身的量级，避免参数量纲差异使统一 λ 对某些参数形同虚设。
 *   注意阻尼在分解【之前】加——加在 A 上，而不是加在解上。
 *
 * 【数值条件的诚实声明】
 *   形成 JᵀJ 会把 J 的条件数平方：κ(JᵀJ) = κ(J)²。
 *   J 条件数 1e8 时 JᵀJ 达 1e16，双精度有效数字耗尽。
 *   拟合问题参数少（n 通常 < 100）、J 不算太病态时本方法最快最省内存；
 *   病态/秩亏场景请换 qr.ts / svd.ts（同目录）。
 *
 * 【复杂度与内存】
 *   时间：O(m·n²) 形成 + O(n³/3) 分解；内存：额外 n²（JᵀJ）+ 2n。
 *   n² 量级的临时分配允许——它是参数规模，不是数据规模 m；
 *   本函数每轮外层迭代只调一次，m×n 量级的分配才是热路径禁忌。
 *
 * 【对外约定】
 *   J 行主序扁平存储（Float64Array，长度 m*n，J[i*n+k] = 第 i 行第 k 列）。
 *   结果写入调用方预分配的 out（长度 n），本函数不返回新数组。
 * ============================================================================
 */

/** 阻尼下限：防止某参数的列全零（模型未用到该参数）时 D 对角元为 0，
 *  λD 救不了它，Cholesky 开方负数直接 NaN。兜底成小正数保证可解。 */
const DIAGONAL_FLOOR = 1e-12;

export function solveByNormalEquations(
  J: Float64Array,            // in ：设计矩阵，行主序 m×n
  r: Float64Array,            // in ：残差向量，长度 m（定号由外层负责）
  m: number,                  // in ：数据点数（J 的行数）
  n: number,                  // in ：参数个数（J 的列数）
  damping: { lambda: number; diagD?: Float64Array },  // in ：λ 与可选的 D
  out: Float64Array           // out：解 Δ，长度 n，调用方预分配
): void {

  /* ------------------------------------------------------------------
   * 第一段：形成 A = JᵀJ（利用对称性只累加上三角）和 g = Jᵀr
   * 逐数据行扫描，一遍完成两个归约，缓存友好的写法。
   * ------------------------------------------------------------------ */
  const A = new Float64Array(n * n);  // JᵀJ，对称，先存上三角
  const g = new Float64Array(n);      // Jᵀr，长度 n

  for (let k = 0; k < m; k++) {           // 遍历每个数据点（J 的每一行）
    const row = k * n;                    // 该行在扁平数组中的起始下标
    const rk = r[k];                      // 缓存 r[k]，内层不用反复下标取
    for (let i = 0; i < n; i++) {
      const Jki = J[row + i];             // 缓存 J[k][i]
      g[i] += Jki * rk;                   // 累加 Jᵀr 的第 i 个分量
      for (let j = i; j < n; j++)         // j 从 i 起：只算上三角 (i ≤ j)
        A[i * n + j] += Jki * J[row + j]; // A[i][j] += J[k][i]·J[k][j]
    }
  }

  // 对称性镜像：A[i][j] = A[j][i]，把上三角复制到下三角。
  // Cholesky 只读下三角，必须补齐才能分解。
  for (let i = 0; i < n; i++)
    for (let j = 0; j < i; j++)           // 严格下三角（j < i）
      A[i * n + j] = A[j * n + i];

  /* ------------------------------------------------------------------
   * 第二段：应用阻尼 A ← A + λ·D
   * D 的选取：显式传入 diagD 优先；否则用 JᵀJ 自身对角元（Marquardt）。
   * 读取对角元发生在加法之前——加完的值不能再当尺度用。
   * ------------------------------------------------------------------ */
  const lambda = damping.lambda;
  if (lambda > 0) {                       // λ = 0 时跳过，纯 Gauss-Newton
    for (let i = 0; i < n; i++) {
      const d = damping.diagD
        ? damping.diagD[i]                // 外部指定的尺度（如 tfjs 路径传来）
        : A[i * n + i];                   // 缺省：JᵀJ 对角元自身
      A[i * n + i] += lambda * Math.max(d, DIAGONAL_FLOOR);
    }
  }
  // 此刻 A 对称正定（正定性由 λ>0 的阻尼兜底；λ=0 且 J 秩亏时
  // Cholesky 内部的 floor 会接管，见 choleskyInPlace 注释）。

  /* ------------------------------------------------------------------
   * 第三段：Cholesky 分解 A = L·Lᵀ（原地，覆盖 A 的下三角）
   * ------------------------------------------------------------------ */
  choleskyInPlace(A, n);

  /* ------------------------------------------------------------------
   * 第四段：前代 L·y = g（下三角求解），y 就地写进 out
   * y[i] = ( g[i] − Σ_{j<i} L[i][j]·y[j] ) / L[i][i]
   * ------------------------------------------------------------------ */
  for (let i = 0; i < n; i++) {
    let s = g[i];                         // 未消去项的累积器
    for (let j = 0; j < i; j++)
      s -= A[i * n + j] * out[j];         // 减去 L[i][j]·y[j]，j < i 走下三角
    out[i] = s / A[i * n + i];            // L[i][i] 即对角（存的就是开方值）
  }

  /* ------------------------------------------------------------------
   * 第五段：回代 Lᵀ·Δ = y（上三角求解），仍就地写 out
   * Δ[i] = ( y[i] − Σ_{j>i} L[j][i]·Δ[j] ) / L[i][i]
   * Lᵀ 的 (i,j) 元 = L 的 (j,i) 元，所以下标是 A[j*n+i]（j > i，下三角）。
   * out 前 i 项此刻已是 Δ 的最终值，前代时它们是中间量 y——
   * 两段共用同一缓冲是安全的：前代自上而下写完，回代自下而上覆盖。
   * ------------------------------------------------------------------ */
  for (let i = n - 1; i >= 0; i--) {
    let s = out[i];                       // 此刻 out[i] 是 y[i]
    for (let j = i + 1; j < n; j++)
      s -= A[j * n + i] * out[j];         // 减 Lᵀ[i][j]·Δ[j] = L[j][i]·Δ[j]
    out[i] = s / A[i * n + i];            // 得到 Δ[i]，就地覆盖
  }
}

/* --------------------------------------------------------------------
 * Cholesky 分解（原地，只写 A 的下三角含对角）。
 * 数学：对每列 i，
 *   L[i][j] = ( A[i][j] − Σ_{k<j} L[i][k]·L[j][k] ) / L[j][j]   (j < i)
 *   L[i][i] = sqrt( A[i][i] − Σ_{k<i} L[i][k]² )
 * 非正定兜底：对角开方前发现 ≤ 0 时压到 DIAGONAL_FLOOR。
 * 这不是数学上正确的处理（正确的做法是报错或转 SVD），但在 LM 语境下
 * 是合理的工程折中——λ>0 时理论上不可能发生，发生的唯一途径是
 * λ=0 且 J 秩亏，此时返回一个“保守的大步长”交给外层 ρ 判据拒绝，
 * 比直接抛异常打断迭代更符合信赖域框架的容错设计。
 * -------------------------------------------------------------------- */
function choleskyInPlace(A: Float64Array, n: number): void {
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {          // 扫下三角含对角（j ≤ i）
      let s = A[i * n + j];                 // 从原始 A[i][j] 出发
      for (let k = 0; k < j; k++)           // 减去已算出的 L 元素的贡献
        s -= A[i * n + k] * A[j * n + k];   // L[i][k]·L[j][k]
      if (i === j) {
        if (s <= 0) s = DIAGONAL_FLOOR;     // 非正定兜底（见函数头注释）
        A[i * n + i] = Math.sqrt(s);        // 对角元：开方
      } else {
        A[i * n + j] = s / A[j * n + j];    // 非对角：除以 L[j][j]
      }
    }
  }
  // 注：A 的上三角此时仍是分解前的旧值（垃圾），但 solve 全程只读
  // 下三角，所以不清零。若未来有人复用 A 的上三角，务必先知道这一点。
}

/* --------------------------------------------------------------------
 * cholSolve：只做“分解好的下三角 L + 右端 g → 解”两段。
 * 单独导出的原因：tfjs GPU 路径的 A、g 在 GPU 上归约完成后直接下载，
 * 不经过本文件的“形成 JᵀJ”阶段（那是 CPU 路径的事），
 * 但收尾的 Cholesky 求解是共用的——p×p 小矩阵，CPU 微秒级。
 * -------------------------------------------------------------------- */
export function cholSolve(L: Float64Array, g: Float64Array,
                          n: number, out: Float64Array): void {
  for (let i = 0; i < n; i++) {             // 前代 L·y = g
    let s = g[i];
    for (let j = 0; j < i; j++) s -= L[i * n + j] * out[j];
    out[i] = s / L[i * n + i];
  }
  for (let i = n - 1; i >= 0; i--) {        // 回代 Lᵀ·Δ = y
    let s = out[i];
    for (let j = i + 1; j < n; j++) s -= L[j * n + i] * out[j];
    out[i] = s / L[i * n + i];
  }
}
