/**
 * 雅可比矩阵计算子模块 - 公式雅可比（不是残差雅可比）
 * ---
 * 简介：
 * - 雅可比矩阵，即计算模型/公式的输出值对模型各参数的偏导数，以反映模型预测值对各参数的敏感性。
 *       J[n, p] = ∂fₙ/∂βₚ`。
 *   式中：n 为数据样本数，p 为参数个数，
 *       f 为模型/公式，fₙ 为第 n 个数据样本的模型/公式输出，
 *       β 为“参数向量”，值为 (β₁, …, βₚ)，是向量。βₚ 为 p 个参数的“参数向量”分量。
 *   对于雅可比矩阵（J矩阵）中的每个值：`J[i][j] = ∂fᵢ/∂βⱼ`
 *   即第 i 个数据样本对应的，该样品条件下的模型/公式输出值对第 j 个参数的偏导数。
 * - 注意1：还有一种雅可比矩阵，是以残差r来形成的：
 *       Jᵣ[n, p] = ∂rₙ/∂βₚ
 *   即：把 f 换成 r，r 即残差、误差。
 *   为了以示区分，我们把本模块的雅可比矩阵称为“公式雅可比矩阵 J”。而把“以残差r为因变量”的雅可比矩阵称为“残差雅可比矩阵 Jᵣ”。
 *   两个雅可比的换算关系：
 *       rₙ = yₙ - fₙ(β)，或更简化的表示：r = y − f
 *       y 是确定值，而 J 本质上是偏微分，所以：
 *       Jᵣ = −J
 * - 注意2：这里需要特别注意的是ODR算法，其除了需要雅可比矩阵，还需要预测函数对自变量的偏导数：
 *   `J[n][p] = ∂f/∂xᵢ`
 *   不过计算原理是一致的，所以也归并到雅可比矩阵计算子模块中。
 * - 主流雅可比方法有3种：
 *   - 解析雅可比：用户手写解析公式，计算量小，但需要用户手动推导公式，且公式复杂时推导困难。
 *   - 自动微分：JS语系下，利用 tfjs-core 库自动求导，计算量小，且可实现 GPU 硬件加速（见 tfjs-auto-diff.ts，待实现）。
 *   - 数值雅可比：有限差分近似，简单通用，无需手推公式；纯 JS 实现，无法 GPU 加速（见 numerical.ts）。
 */

